def wrap_untrusted(tool_name: str, content: str) -> str:
    escaped = content.replace("<untrusted_tool_output", "&lt;untrusted_tool_output").replace(
        "</untrusted_tool_output>", "&lt;/untrusted_tool_output&gt;"
    )
    return f'<untrusted_tool_output tool="{tool_name}">\n{escaped}\n</untrusted_tool_output>'
